#!/usr/bin/env bash
# يفحص جاهزية تسلسل الخروج قبل أول أمر خروج.
# يفشل إن غاب ختم هرمي معتمد (ن ← اعتماد م٢ ← اعتماد م١) أو وارِدة من أي دور.
# خ-٢ (اعتماد م١ ٢٠٢٦-٠٩-١٨): يُمرَّر سجل المهمة مسارًا صريحًا — ولا تخمين بـ«أحدث سجل».
#   السبب المقيس: `ls | sort | tail -1` يقدّم سجلًا قديمًا (م٤) على سجل المهمة ⇒ أخضر زائف (واقعة م-١).
# الصيغة: فحص-الخروج.sh [ن|م٢|م١] <مسار سجل الإقفال والخروج داخل القناة/العمل>
set -euo pipefail
cd "$(dirname "$0")/.."

CH=القناة
if [ ! -d "$CH" ]; then
  echo 'ممنوع: مجلد القناة غير موجود؛ شغّل فتح.sh أولًا.' >&2
  exit 1
fi

log="${2:-}"
if [ -z "$log" ]; then
  echo 'ممنوع الخروج: لا سجل مهمة محدَّد — مرّر مسار سجل الإقفال والخروج صريحًا ولا تخمّن:' >&2
  echo '  الصيغة: فحص-الخروج.sh [ن|م٢|م١] القناة/العمل/سجل-الإقفال-والخروج-*.md' >&2
  exit 1
fi
case "$log" in
  "$CH"/العمل/سجل-الإقفال-والخروج-*.md) : ;;
  *) echo "ممنوع الخروج: المسار ليس سجل مهمة داخل القناة (خ-٢): $log — المطلوب تحت $CH/العمل/ ويبدأ بـ«سجل-الإقفال-والخروج-»." >&2; exit 1 ;;
esac
if [ ! -f "$log" ]; then
  echo "ممنوع الخروج: لا وجود لسجل المهمة الممرَّر (خ-٢): $log" >&2
  exit 1
fi
echo "أفحص: $log"

# التجميد (٢٠٢٦-٠٩-١٨): لا خروج حتى إتمام البنود المفتوحة — إلا برفع صريح من م١.
if compgen -G "$CH"/العمل/إعلان-تجميد-أوامر-الخروج-*.md >/dev/null 2>&1 \
   && ! compgen -G "$CH"/العمل/رفع-تجميد-أوامر-الخروج-*.md >/dev/null 2>&1; then
  echo 'ممنوع الخروج: أوامر الخروج مُجمَّدة بأمر المالك («لا خروج حتى الانتهاء») — تُرفع بعد إتمام البنود المفتوحة بإعلان رفع من م١ (تجميد خ-٨).' >&2
  exit 1
fi

fail=0
val() { sed -n "s/^$1: *//p" "$log" | tail -n 1; }
filled() { [ -n "$1" ] && ! printf '%s' "$1" | grep -Eq '^[ .]+$|^$|لم يُشغّل بعد$' ; }

check_seal() {
  local key="$1" label="$2" v
  v="$(val "$key" || true)"
  if ! filled "$v"; then
    echo "غائب أو غير مكتمل: $label ($key)" >&2
    fail=1
  else
    echo "  حاضر: $label"
  fi
}

check_ward() {
  local key="$1" label="$2" v
  v="$(val "$key" || true)"
  if ! filled "$v"; then
    echo "غائب: $label ($key)" >&2
    fail=1
  elif [ ! -f "$CH/$v" ]; then
    echo "مرجع ناقص: $label يشير إلى ملف غير موجود داخل القناة: $v" >&2
    fail=1
  else
    echo "  حاضر: $label ← $v"
  fi
}

echo '[١] الأختام الهرمية (لا يُعتد بالأدنى بلا اعتماد الأعلى):'
check_seal 'ختم-المنفذ' 'ختم المنفذ'
check_seal 'اعتماد-المستشار-الثاني' 'اعتماد المستشار الثاني لختم المنفذ'
check_seal 'اعتماد-المستشار-الأول' 'ختم المستشار الأول'

echo '[٢] الواردات المعرفية الثلاث (بعد الأختام وقبل الأوامر):'
check_ward 'واردة-المنفذ' 'واردة المنفذ'
check_ward 'واردة-المستشار-الثاني' 'واردة المستشار الثاني'
check_ward 'واردة-المستشار-الأول' 'واردة المستشار الأول'

# [٣] قفل المراقب الحي: لا إقرار خروج لدور ومراقبه ما زال مسلّحًا.
# الصيغة: فحص-الخروج.sh [ن|م٢|م١] · م١ في قفله الأخير يفحص الثلاثة.
echo '[٣] نزع سلاح المراقب الحي (العين انتظر.sh والقلب نبض.sh):'
check_watch() {
  local r="$1" pf pp pid weapon armed=0
  pf=".watch-pid-$r"; pp=".pulse-pid-$r"
  for weapon in "$pf" "$pp"; do
    if [ -f "$weapon" ]; then
      pid="$(cat "$weapon" 2>/dev/null || true)"
      if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
        echo "سلاح حي لـ$r (العملية $pid في $weapon) — انزعه قبل الإقرار: نبض.sh سلمت/أوقف $r يوقف القلب، وأوقف العين، واحذف الملف." >&2
        fail=1; armed=1
      else
        rm -f "$weapon"; echo "  $r: ملف سلاح قديم ($weapon) لعملية منتهية، نُظّف."
      fi
    fi
  done
  [ "$armed" = 0 ] && [ ! -f "$pf" ] && [ ! -f "$pp" ] && echo "  $r: لا عين ولا قلب مسلّح."
}
case "${1:-}" in
  ن)   check_watch 'ن' ;;
  م٢)  check_watch 'م٢' ;;
  م١)  check_watch 'ن'; check_watch 'م٢'; check_watch 'م١' ;;
  "")  : ;;
  *)   echo "وسيط دور غير معروف: $1 (ن|م٢|م١)" >&2; fail=1 ;;
esac

if [ "$fail" -ne 0 ]; then
  echo 'النتيجة: ممنوع بدء تسلسل الخروج — استوفِ النواقص ثم أعد الفحص.' >&2
  exit 1
fi
echo 'النتيجة: الإقفال مكتمل هرميًا ووارداته حاضرة — ابدأ أمر الخروج الأول (للمنفذ).'
