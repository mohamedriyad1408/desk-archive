def sha256(p: Path) -> str:
    """البصمة الحاكمة: SHA-256 كاملة ٦٤ خانة (ج٥٧) — المختصر للعرض فقط."""
    return hashlib.sha256(p.read_bytes()).hexdigest()

def span_of(phrase: str, p: Path):
    """أول سطر يحوي العبارة في الحامل — لقيد quote_span"""
    if not phrase or not p.exists():
        return None
    try:
        for i, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            j = line.find(phrase)
            if j >= 0:
                return f"L{i}#{j}-{j+len(phrase)}"
    except Exception:
        pass
    return None

