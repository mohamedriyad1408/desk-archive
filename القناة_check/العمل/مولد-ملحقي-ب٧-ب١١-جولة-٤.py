def _pinned_sha_from_vault():
    """قياس بصمة النسخة المعلنة من الحجم نفسه — الثابت يُثبت قياسًا لا ثقة.
    (منقولة إلى الرأس بطلب الباب ٢: رفض بلا مفتاح لا يترك أثرًا في الشجرة.)"""
    import os as _os, subprocess as _sp, tempfile as _tf
    if not _os.environ.get("MIFTAH"):
        print(f"سدّ S-13 (N-07): MIFTAH غير مضبوط — لا يُكتب جرد بلا قياس بصمة النسخة المعلنة ({PINNED_AT_HDR}). صدِّر المفتاح ثم أعد التوليد.")
        sys.exit(1)
    vol = CH.parent / "vault" / (PINNED_AT_HDR.split(" @ ")[0].split("/")[-1] + ".enc")
    if not vol.exists():
        print(f"سدّ S-13 (N-07): الحجم المعلن مفقود: {vol} — لا تثبيت بلا حجته.")
        sys.exit(1)
    with _tf.TemporaryDirectory() as td:
        dec = _sp.run(["openssl", "enc", "-d", "-aes-256-cbc", "-pbkdf2", "-iter", "600000",
                       "-salt", "-pass", "env:MIFTAH", "-in", str(vol)], capture_output=True)
        if dec.returncode != 0:
            print("سدّ S-13 (N-07): فك الحجم المعلن فشل (المفتاح لا يفتحه) — لا تثبيت بلا قياس.")
            sys.exit(1)
        if _sp.run(["tar", "-xz", "-C", td], input=dec.stdout, capture_output=True).returncode != 0:
            print("سدّ S-13 (N-07): فك أرشيف الحجم المعلن فشل.")
            sys.exit(1)
        for root, _dirs, files in _os.walk(td):
            for f in files:
                if f.endswith("سجل-المدير.md"):
                    return hashlib.sha256(open(_os.path.join(root, f), "rb").read()).hexdigest()
    print("سدّ S-13 (N-07): ملف المصدر الحي غير موجود داخل الحجم المعلن.")
    sys.exit(1)

