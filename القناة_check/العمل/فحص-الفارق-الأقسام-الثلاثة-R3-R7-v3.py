def run_diff(v1: str, v3: str):
    H = hunks(v1, v3)
    per = {'قسم ٠': [], 'قسم ٢': [], 'قسم ٣': []}
    undeclared = []
    for tag, i1, i2, j1, j2, old, new in H:
        blob = old + '\n' + new
        sec = classify(blob)
        if sec == 'غير معلن':
            undeclared.append((tag, j1, (new or old).split('\n')[0][:80]))
        else:
            per[sec].append((tag, j1, (new or old).split('\n')[0][:60]))
    return H, per, undeclared

