# ممنوعات: واو المحشوة بحرفها · أي تحرير خارج القائمة المعلنة.
import hashlib, re, sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
SRC = BASE / 'الدستور-٣٫٠-مسودة-R3-R5-2026-09-29.md'
DST = BASE / 'الدستور-٣٫٠-النهائية-R3-R6-2026-09-30.md'

fails = []
def rep(old, new, tag):
    global t
    if old not in t:
        fails.append(f"FAIL: مرساة مفقودة [{tag}]: {old[:70]}…")
        return
    if t.count(old) != 1:
        fails.append(f"FAIL: مرساة غير فريدة [{tag}] ({t.count(old)} مواضع)")
        return
    t = t.replace(old, new)

t = SRC.read_text(encoding='utf-8')

# ── ز١: العنوان ──
rep('# دستور التجنيد — بروتوكول التشغيل الذاتي — النسخة ٣٫٠ (R3 المدمجة)',
    '# دستور التجنيد — بروتوكول التشغيل الذاتي — النسخة ٣٫٠ (R3-R6 النهائية)', 'ز١')

# ── ز٢: الصفة ──
rep('**الصفة:** مسودة مدمجة من جلسة الإجماع (الميثاق الخماسي) — تُعرض على المحقق المستقل للحكم المدمج الواحد ثم تواقيع الفريق ثم اعتماد سلطة القرار. **حتى كلمتها، النسخة النافذة هي ٢٫٩ بحرفها.**',
    '**الصفة:** النسخة النهائية العربية من جلسة الإجماع (الميثاق الخماسي) بقرار سلطة القرار «أغلق كل شيء» — حُكمت بثلاثة أحكام مستقلة، ووُقعت سلسلتها R3-R5 بالأحبار الأربعة (ق ← م١ ← م٢ ← ن)، وهذه إصدارة الإقفال المعروضة عليها للاعتماد. **حتى اعتمادها، النسخة النافذة هي ٢٫٩ بحرفها.**',
    'ز٢')

# ── ز٣: قسم صفر/٦ ──
rep('٦. لا يُسلَّم الشات وفي رسالة البدء نقص من الأربعة؛ فإن غاب شيء طلبه الوكيل أول مرة وسجّله عائقًا في الحالة.',
    '٦. لا يُسلَّم الشات وفي رسالة البدء نقص مما يوجبه البند ٢؛ فإن غاب شيء طلبه الوكيل أول مرة وسجّله عائقًا في الحالة.',
    'ز٣')

# ── ز٤: ركاكة عقد الطبقة الرابعة ──
rep('tests: عند بناء أدوات المجال عند بوابة النفاذ',
    'tests: عند بناء أدوات المجال في بوابة النفاذ', 'ز٤')

# ── ز٥: قانون المساحة — صيغة قياس ن ق-٠١٠ ──
rep('الاستنساخ في `/tmp` لعمر الجولة فقط (خارج اللقطة) ويُمحى بعدها.',
    'الاستنساخ في مساحة مؤقتة خارج اللقطة (المرجعية `/tmp`) لعمر الجولة فقط ويُمحى بعدها. '
    '**المسار المرجعي هو الاستنساخ الجزئي (partial clone) — قياس ق-٠١٠:** `git clone --filter=blob:none --no-checkout` ثم '
    '`git sparse-checkout init --no-cone` وضم `scripts` و`نبض` وأحدث حجم `vault/v-NNN.enc` — بذروة مقيسة ≈٣٠MB '
    'مهما كثرت الأحجام (المقاس: 28MB عند ٥٦٠+ حجمًا مقابل ≈1.5GB للاستنساخ الكامل)؛ فالاستنساخ الكامل استثناء '
    'يُعلن سببه في إعلان التجنيد، وكذلك أي انحراف قسري عن المسار المرجعي. وللختم في الجزئي: يُوسَّع النمط ليشمل '
    'أي حجم جديد على البعيد قبل الختم، وتُستعمل إضافة `--sparse` في أداة الختم. وكل كتابة أداة تُجرَّب في مجلد '
    'مؤقت أو مستنسخ معزول بفحص `diff -rq` قبل/بعد = صفر (S-16) — وشجرة التشغيل لا تُمَس.',
    'ز٥')

# ── ز٧: جدول الناسخ (العدد ورأس النطاق) ──
rep('`العمل/ملحق-ب١١-جرد-المصادر-v2.json` (٦٩ مصدرًا',
    '`العمل/ملحق-ب١١-جرد-المصادر-v2.json` (٧٦ مصدرًا', 'ز٧-أ')
rep('رأس نطاق «مسودة ٣٫٠» = R3-R5',
    'رأس نطاق «النسخة ٣٫٠» = R3-R6', 'ز٧-ب')

# ── ز٦: إصدارة العقود الثلاثة (قبل حساب البصمات) ──
n_ver = t.count('version: R3-R5')
if n_ver != 3:
    fails.append(f"FAIL: مراسي version: R3-R5 ليست ثلاثًا ({n_ver})")
t = t.replace('version: R3-R5', 'version: R3-R6')

# ── ز٨: سطر التوقيع ──
rep('**Signed-By: ق — الكاتب والأمين — R3-R5: دمج جلسة الإجماع + علاجات الحكم المدمج والمؤجل (R-01…R-11 ثم N-01…N-06) — النافذ ٢٫٩.**',
    '**Signed-By: ق — الكاتب والأمين — R3-R6: النسخة النهائية للإقفال بقرار المالك «أغلق كل شيء» فوق R3-R5 الموقَّعة من الأربعة (R-01…R-11 ثم N-01…N-06 ثم الإقفال) — النافذ ٢٫٩ حتى اعتماد المالك.**',
    'ز٨')

if fails:
    print('\n'.join(fails))
    print('فشل المولد — لا يُكتب أثر.')
    sys.exit(1)

# ── ز٦ (تكملة): بصمات التجميد الجديدة — تُحسب من الحقول السبعة النهائية (version: R3-R6) ──
new_hashes = []
lines = t.split('\n')
for i, line in enumerate(lines):
    if 'عقد الطبقة (الحقول الثمانية)' in line:
        m = re.search(r'profile_id: (.*) · hash: ([0-9a-f]{64})', line)
        if not m:
            print(f"FAIL: عقد بلا بصمة عند السطر {i+1}")
            sys.exit(1)
        seven = 'profile_id: ' + m.group(1)
        h = hashlib.sha256(seven.encode('utf-8')).hexdigest()
        lines[i] = line.replace('hash: ' + m.group(2), 'hash: ' + h)
        new_hashes.append(h)
t = '\n'.join(lines)
if len(new_hashes) != 3:
    print(f"FAIL: العقود ليست ثلاثًا ({len(new_hashes)})")
    sys.exit(1)

# ── تحقق ذاتي: كل بصمة تطابق حقولها داخل المستند النهائي ──
for line in t.split('\n'):
    if 'عقد الطبقة (الحقول الثمانية)' in line:
        m = re.search(r'profile_id: (.*) · hash: ([0-9a-f]{64})', line)
        assert hashlib.sha256(('profile_id: ' + m.group(1)).encode('utf-8')).hexdigest() == m.group(2), "بصمة لا تطابق حقولها!"

DST.write_text(t, encoding='utf-8')
n_lines = t.count('\n') + 1
print(f"النسخة النهائية R3-R6: {n_lines} سطرًا (بمقياس المولد)")
print(f"بصمات العقود الثلاث الجديدة: {' · '.join(h[:12] + '…' for h in new_hashes)}")
print(f"sha256(R3-R6) = {hashlib.sha256(DST.read_bytes()).hexdigest()}")
